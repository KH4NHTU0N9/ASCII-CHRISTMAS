/**
 * Fetches the live treeEngine.js file over HTTP so the code pane literally
 * reflects the running code, falling back cleanly if opened via file://.
 */
export async function loadLiveCodeSource() {
  try {
    if (window.location.protocol === 'file:') {
      return FALLBACK_SOURCE;
    }
    const res = await fetch('./src/treeEngine.js', { cache: 'no-store' });
    if (!res.ok) return FALLBACK_SOURCE;
    return await res.text();
  } catch {
    return FALLBACK_SOURCE;
  }
}
